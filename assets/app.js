function initContactForm(t) {
  const form = document.getElementById("contact-form");
  const messageBox = document.getElementById("form-message");
  if (!form || !messageBox) return;
  const submitButton = form.querySelector('button[type="submit"]');

  const encodedAddress = form.getAttribute("data-mail");
  if (!encodedAddress) return;

  let emailAddress = "";
  try {
    emailAddress = atob(encodedAddress);
  } catch (error) {
    messageBox.textContent = t.contact.unavailable;
    return;
  }

  if (!emailAddress) return;

  form.setAttribute("action", `https://formsubmit.co/${emailAddress}`);
  form.setAttribute("method", "POST");

  const nextInput = form.querySelector('input[name="_next"]');
  if (nextInput) {
    const nextUrl = new URL(window.location.href);
    nextUrl.searchParams.set("sent", "1");
    nextUrl.hash = "contact";
    nextInput.value = nextUrl.toString();
  }

  const queryParams = new URLSearchParams(window.location.search);
  if (queryParams.get("sent") === "1") {
    messageBox.textContent = t.contact.success;
    queryParams.delete("sent");
    const newQuery = queryParams.toString();
    const newUrl = `${window.location.pathname}${newQuery ? `?${newQuery}` : ""}${window.location.hash}`;
    window.history.replaceState({}, "", newUrl);
  }

  form.addEventListener("submit", (event) => {
    const data = new FormData(form);
    const name = String(data.get("name") || "").trim();
    const email = String(data.get("email") || "").trim();
    const message = String(data.get("message") || "").trim();
    const hasConsent = data.get("privacy-consent") === "on";

    if (!name || !email || !message) {
      event.preventDefault();
      messageBox.textContent = t.contact.missing;
      return;
    }

    if (!hasConsent) {
      event.preventDefault();
      messageBox.textContent = t.contact.needConsent;
      return;
    }

    const honeyValue = String(data.get("_honey") || "").trim();
    if (honeyValue) {
      event.preventDefault();
      messageBox.textContent = t.contact.blocked;
      return;
    }

    messageBox.textContent = t.contact.sending;
    if (submitButton) submitButton.disabled = true;
  });
}

function initFooterYear() {
  const yearElement = document.getElementById("year");
  if (!yearElement) return;
  yearElement.textContent = String(new Date().getFullYear());
}

function initLangSwitcher(lang) {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-lang-link]").forEach((link) => {
    const target = link.getAttribute("data-lang-link");
    link.classList.toggle("is-active", target === lang);
  });
}

